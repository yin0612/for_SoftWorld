// 輔助函數：產生隨機日期 (2024-01-01 到 2026-08-31)
function getRandomDate() {
    const start = new Date(2024, 0, 1).getTime();
    const end = new Date(2026, 7, 31).getTime();
    return new Date(start + Math.random() * (end - start));
}

